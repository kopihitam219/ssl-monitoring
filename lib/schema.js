/** Data awal: group Local / Public / Partner (hanya kalau belum ada group sama sekali). */
export async function seed(db) {
  const n = (await db.get('SELECT COUNT(*) AS n FROM dashboard_groups')).n;
  if (Number(n) > 0) return;
  const t = new Date().toISOString();
  for (const [i, name] of ['Local', 'Public', 'Partner'].entries()) {
    await db.run('INSERT INTO dashboard_groups (name, sort, created_at) VALUES (?, ?, ?)', name, i + 1, t);
  }
}
